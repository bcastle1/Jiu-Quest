"""Import the five showcase fighter cards for the Overview page.

The cards are generated illustrations in the style of the Unreal athlete. They
are not Unreal renders. The image job writes five PNG files and receipt.json;
this script checks every file against that receipt, trims each picture to
exactly four by five, sizes it for the page and writes:

    public/assets/showcase/<card>.webp
    src/showcaseCards.data.js

Usage:
    python3 -I tools/import_showcase_cards.py <showcase-cards/out>

The source pictures are not in this repository. Their SHA-256 values are
written into the data module for the tests to pin. Requires Pillow.
"""
import hashlib
import json
import pathlib
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public" / "assets" / "showcase"
MODULE = ROOT / "src" / "showcaseCards.data.js"
# Card file name and the name printed on the card, in page order.
CARDS = (
    ("crimson-guard", "Crimson Guard"),
    ("void-striker", "Void Striker"),
    ("blue-surge", "Blue Surge"),
    ("emerald-guard", "Emerald Guard"),
    ("gold-hunter", "Gold Hunter"),
)
# Published size: four by five, enough for a card on a high-density phone.
SIZE = (900, 1125)
QUALITY = 84


def fail(message):
    raise SystemExit(f"import_showcase_cards: {message}")


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    source = pathlib.Path(sys.argv[1])
    receipt = json.loads((source / "receipt.json").read_text(encoding="utf-8"))
    listed = {pathlib.PurePath(entry["file"].replace("\\", "/")).name: entry for entry in receipt}
    if sorted(listed) != sorted(f"{slug}.png" for slug, _ in CARDS):
        fail(f"receipt.json must list exactly the five cards, not {sorted(listed)}")

    PUBLIC.mkdir(parents=True, exist_ok=True)
    for stale in PUBLIC.iterdir():
        stale.unlink()
    cards = []
    for slug, label in CARDS:
        entry = listed[f"{slug}.png"]
        data = (source / f"{slug}.png").read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        if len(data) != entry["bytes"] or digest != entry["sha256"]:
            fail(f"{slug}.png does not match receipt.json")
        image = Image.open(source / f"{slug}.png").convert("RGB")
        width, height = image.size
        if (width, height) != (entry["width"], entry["height"]) or width < 1024:
            fail(f"{slug}.png is {width} x {height}; the receipt and a width of at least 1024 are required")
        # Trim evenly to exactly four by five; refuse a picture that needs more than a sliver.
        if width * 5 > height * 4:
            keep = (height * 4 // 5, height)
        else:
            keep = (width, width * 5 // 4)
        if keep[0] < width * 0.97 or keep[1] < height * 0.97:
            fail(f"{slug}.png is not close to four by five ({width} x {height})")
        left, top = (width - keep[0]) // 2, (height - keep[1]) // 2
        card = image.crop((left, top, left + keep[0], top + keep[1])).resize(SIZE, Image.LANCZOS)
        path = PUBLIC / f"{slug}.webp"
        card.save(path, "WEBP", quality=QUALITY, method=6)
        published = path.read_bytes()
        cards.append({
            "id": slug,
            "label": label,
            "src": f"/assets/showcase/{slug}.webp",
            "width": SIZE[0],
            "height": SIZE[1],
            "bytes": len(published),
            "sha256": hashlib.sha256(published).hexdigest(),
            "sourceSha256": digest,
        })

    MODULE.write_text(
        "// Generated by tools/import_showcase_cards.py. Do not edit by hand.\n"
        "// The five example-fighter cards on the Overview page: generated illustrations\n"
        "// in the style of the Unreal athlete, not Unreal renders.\n"
        f"const cards = {json.dumps(cards, indent=2)};\n\n"
        "export default Object.freeze(cards.map((card) => Object.freeze(card)));\n",
        encoding="utf-8",
    )
    print(json.dumps({"cards": len(cards), "bytes": sum(card["bytes"] for card in cards), "size": list(SIZE)}, indent=2))


if __name__ == "__main__":
    main()
