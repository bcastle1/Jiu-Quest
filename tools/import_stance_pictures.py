"""Import the seven stance pictures for the Profile's stance picker.

The pictures are generated illustrations of the Unreal athlete in each fighting
stance, made to match the Unreal renders. They are not Unreal renders. The
image job writes seven PNG files and receipt.json; this script checks every
file against that receipt, trims each picture to exactly four by five, sizes it
for the picker and writes:

    public/assets/unreal-stances/<stance>.webp
    src/unreal/stancePictures.data.js

Usage:
    python3 -I tools/import_stance_pictures.py <stance-cards/out>

The source pictures are not in this repository. Their SHA-256 values are
written into the data module for the tests to pin. Requires Pillow.
"""
import hashlib
import json
import pathlib
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public" / "assets" / "unreal-stances"
MODULE = ROOT / "src" / "unreal" / "stancePictures.data.js"
# Picture file name and the stance it shows, as the game names stances.
STANCES = (
    ("wrestling", "wrestling stance"),
    ("sumo", "sumo base"),
    ("boxing", "boxer shell"),
    ("karate", "karate stance"),
    ("muay-thai", "muay thai guard"),
    ("sambo", "sambo crouch"),
    ("capoeira", "capoeira rhythm"),
)
# Published size: four by five. The picker shows it small; this leaves room to
# show it larger on a high-density screen.
SIZE = (480, 600)
QUALITY = 84


def fail(message):
    raise SystemExit(f"import_stance_pictures: {message}")


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    source = pathlib.Path(sys.argv[1])
    receipt = json.loads((source / "receipt.json").read_text(encoding="utf-8"))
    listed = {pathlib.PurePath(entry["file"].replace("\\", "/")).name: entry for entry in receipt}
    if sorted(listed) != sorted(f"{slug}.png" for slug, _ in STANCES):
        fail(f"receipt.json must list exactly the seven stances, not {sorted(listed)}")

    PUBLIC.mkdir(parents=True, exist_ok=True)
    for stale in PUBLIC.iterdir():
        stale.unlink()
    pictures = []
    for slug, stance in STANCES:
        entry = listed[f"{slug}.png"]
        data = (source / f"{slug}.png").read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        if len(data) != entry["bytes"] or digest != entry["sha256"]:
            fail(f"{slug}.png does not match receipt.json")
        image = Image.open(source / f"{slug}.png").convert("RGB")
        width, height = image.size
        if (width, height) != (entry["width"], entry["height"]) or width < 1024:
            fail(f"{slug}.png is {width} x {height}; the receipt and a width of at least 1024 are required")
        # Trim evenly to exactly four by five; refuse a picture that needs more than a sliver.
        if width * 5 > height * 4:
            keep = (height * 4 // 5, height)
        else:
            keep = (width, width * 5 // 4)
        if keep[0] < width * 0.97 or keep[1] < height * 0.97:
            fail(f"{slug}.png is not close to four by five ({width} x {height})")
        left, top = (width - keep[0]) // 2, (height - keep[1]) // 2
        picture = image.crop((left, top, left + keep[0], top + keep[1])).resize(SIZE, Image.LANCZOS)
        path = PUBLIC / f"{slug}.webp"
        picture.save(path, "WEBP", quality=QUALITY, method=6)
        published = path.read_bytes()
        pictures.append({
            "stance": stance,
            "src": f"/assets/unreal-stances/{slug}.webp",
            "width": SIZE[0],
            "height": SIZE[1],
            "bytes": len(published),
            "sha256": hashlib.sha256(published).hexdigest(),
            "sourceSha256": digest,
        })

    MODULE.write_text(
        "// Generated by tools/import_stance_pictures.py. Do not edit by hand.\n"
        "// The Unreal athlete in each fighting stance, for the Profile's stance picker:\n"
        "// generated illustrations made to match the Unreal renders, not Unreal renders.\n"
        f"const pictures = {json.dumps(pictures, indent=2)};\n\n"
        "export default Object.freeze(pictures.map((picture) => Object.freeze(picture)));\n",
        encoding="utf-8",
    )
    print(json.dumps({"pictures": len(pictures), "bytes": sum(picture["bytes"] for picture in pictures), "size": list(SIZE)}, indent=2))


if __name__ == "__main__":
    main()
