const blueMoves = blueBeltGuide.techniques.map((technique, index) => {
  const [id, startingPositionId, category, starts, endsIn, weight] = blueBeltMetadata[index];
  const startingPosition = blueBeltPositionGroups.find((group) => group.id === startingPositionId).label;
  return {
    ...technique, id, belt: 'blue', type: 'technical', category,
    startingPositionId, startingPosition, starts, good: [...starts], poor: [],
    endsIn, weight, isSubmission: category === 'submission',
    phase: { submission: 'Finish', escape: 'Escape', takedown: 'Takedown', sweep: 'Sweep', transition: 'Transition', control: 'Control', defense: 'Defend' }[category],
    description: '',
    steps: technique.stepDetails.map((step) => step.runs.map((run) => run.text).join('')),
  };
});

